# -*- coding: utf-8 -*-
"""
RVE几何文件导出模块
====================
将HPD-RVE生成的RVE模型导出为DAMASK兼容格式 (.geom) 和通用格式 (.vtk)

DAMASK .geom格式说明:
- 文本格式, 每行定义一个material point
- 格式: x y z grain_id phase_id orientation(phi1, Phi, phi2)
- 用于DAMASK Grid求解器 (谱方法)

VTK格式:
- 用于ParaView可视化
- 支持结构化网格 (STRUCTURED_POINTS/IMAGE_DATA)
"""

import numpy as np
from typing import Dict, List, Optional, Tuple
import json
import os


def export_rve_to_geom(rve_result: Dict,
                        output_path: str = "rve.geom",
                        grid_size: int = 64,
                        rve_size_um: float = 100.0) -> str:
    """
    将HPD-RVE模型导出为DAMASK .geom格式

    Args:
        rve_result: HPD-RVE pipeline的输出结果
        output_path: 输出文件路径
        grid_size: 网格分辨率 (N×N×N)
        rve_size_um: RVE尺寸 (µm)

    Returns:
        str: 输出文件路径
    """
    np.random.seed(42)

    # 提取相信息
    phases = rve_result.get("phases", [])
    grain_summary = {}
    if "grain_summary" in rve_result:
        grain_summary = rve_result["grain_summary"]
    elif "param_files" in rve_result:
        for pf in rve_result["param_files"]:
            for pi in pf.get("phases", []):
                pname = pi["phase_name"]
                if pname not in grain_summary:
                    grain_summary[pname] = {
                        "volume_fraction": pi.get("volume_fraction", 0.5),
                        "lattice_structure": pi.get("lattice_structure", "BCC"),
                        "num_grains": pi.get("num_grains", 50),
                        "mean_grain_size": pi.get("mean_grain_size", 10.0),
                    }

    # 生成微观结构 (Voronoi tessellation)
    print(f"  Generating microstructure: {grid_size}×{grid_size}×1 grid")
    print(f"  RVE size: {rve_size_um} µm")

    # 计算晶粒种子点
    n_phases = len(grain_summary)
    all_seeds = []
    phase_ids = []
    grain_ids_list = []

    phase_names = list(grain_summary.keys())
    for p_idx, pname in enumerate(phase_names):
        info = grain_summary[pname]
        n_grains = info.get("num_grains", 50)
        # 种子点随机分布
        seeds = np.random.rand(n_grains, 2) * grid_size
        all_seeds.extend(seeds.tolist())
        phase_ids.extend([p_idx] * n_grains)
        grain_ids_list.extend(range(len(grain_ids_list),
                                     len(grain_ids_list) + n_grains))

    all_seeds = np.array(all_seeds)
    n_total_grains = len(all_seeds)

    # 生成取向
    grain_orientations = []
    for _ in range(n_total_grains):
        phi1 = np.random.uniform(0, 2*np.pi)
        Phi = np.random.uniform(0, np.pi)
        phi2 = np.random.uniform(0, 2*np.pi)
        grain_orientations.append((phi1, Phi, phi2))

    # 为每个像素分配最近种子
    grain_map = np.zeros((grid_size, grid_size), dtype=int)
    phase_map = np.zeros((grid_size, grid_size), dtype=int)

    for i in range(grid_size):
        for j in range(grid_size):
            dists = np.sum((all_seeds - [j, i])**2, axis=1)
            idx = np.argmin(dists)
            grain_map[i, j] = grain_ids_list[idx]
            phase_map[i, j] = phase_ids[idx]

    # 写入.geom文件
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(f"# DAMASK Geometry File\n")
        f.write(f"# Generated by HPD-RVE Pipeline\n")
        f.write(f"# Grid: {grid_size}×{grid_size}×1\n")
        f.write(f"# RVE size: {rve_size_um} µm\n")
        f.write(f"# Phases: {', '.join(phase_names)}\n")
        f.write(f"# Total grains: {n_total_grains}\n")
        f.write(f"# Format: x y z grain phase phi1 Phi phi2\n")
        f.write(f"# header\n")

        cell_size = rve_size_um / grid_size
        for i in range(grid_size):
            for j in range(grid_size):
                x = (j + 0.5) * cell_size
                y = (i + 0.5) * cell_size
                z = cell_size / 2.0  # 单层
                g = grain_map[i, j]
                p = phase_map[i, j]
                phi1, Phi, phi2 = grain_orientations[g]
                f.write(f"{x:.6e} {y:.6e} {z:.6e} {g} {p} "
                        f"{phi1:.6f} {Phi:.6f} {phi2:.6f}\n")

    print(f"  Exported {grid_size*grid_size} material points to {output_path}")
    print(f"  {n_total_grains} grains, {n_phases} phases")
    return output_path


def export_rve_to_vtk(rve_result: Dict,
                       output_path: str = "rve.vtk",
                       grid_size: int = 64,
                       rve_size_um: float = 100.0) -> str:
    """
    将HPD-RVE模型导出为VTK ImageData格式 (用于ParaView)

    Args:
        rve_result: HPD-RVE pipeline的输出结果
        output_path: 输出文件路径
        grid_size: 网格分辨率
        rve_size_um: RVE尺寸

    Returns:
        str: 输出文件路径
    """
    # 复用geom导出的微观结构生成逻辑
    # 先导出为geom, 再转换

    np.random.seed(42)

    phases = rve_result.get("phases", [])
    grain_summary = {}

    # 提取相信息 (与export_rve_to_geom相同逻辑)
    if "grain_summary" in rve_result:
        grain_summary = rve_result["grain_summary"]
    elif "param_files" in rve_result:
        for pf in rve_result["param_files"]:
            for pi in pf.get("phases", []):
                pname = pi["phase_name"]
                if pname not in grain_summary:
                    grain_summary[pname] = {
                        "volume_fraction": pi.get("volume_fraction", 0.5),
                        "lattice_structure": pi.get("lattice_structure", "BCC"),
                        "num_grains": pi.get("num_grains", 50),
                    }

    # 生成微观结构
    phase_names = list(grain_summary.keys())
    all_seeds = []
    phase_ids = []
    grain_ids_list = []

    for p_idx, pname in enumerate(phase_names):
        info = grain_summary[pname]
        n_grains = info.get("num_grains", 50)
        seeds = np.random.rand(n_grains, 2) * grid_size
        all_seeds.extend(seeds.tolist())
        phase_ids.extend([p_idx] * n_grains)
        grain_ids_list.extend(range(len(grain_ids_list),
                                     len(grain_ids_list) + n_grains))

    all_seeds = np.array(all_seeds)
    n_total_grains = len(all_seeds)

    grain_map = np.zeros((grid_size, grid_size), dtype=int)
    phase_map = np.zeros((grid_size, grid_size), dtype=int)

    for i in range(grid_size):
        for j in range(grid_size):
            dists = np.sum((all_seeds - [j, i])**2, axis=1)
            idx = np.argmin(dists)
            grain_map[i, j] = grain_ids_list[idx]
            phase_map[i, j] = phase_ids[idx]

    # 写入VTK ImageData格式
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write("# vtk DataFile Version 3.0\n")
        f.write("HPD-RVE Generated Microstructure\n")
        f.write("ASCII\n")
        f.write("DATASET STRUCTURED_POINTS\n")
        f.write(f"DIMENSIONS {grid_size} {grid_size} 1\n")
        f.write(f"ORIGIN 0.0 0.0 0.0\n")
        f.write(f"SPACING {rve_size_um/grid_size:.6f} "
                f"{rve_size_um/grid_size:.6f} 1.0\n")
        f.write(f"POINT_DATA {grid_size * grid_size}\n")

        # Grain ID field
        f.write("SCALARS grain_id int 1\n")
        f.write("LOOKUP_TABLE default\n")
        for i in range(grid_size):
            for j in range(grid_size):
                f.write(f"{grain_map[i, j]}\n")

        # Phase ID field
        f.write("SCALARS phase_id int 1\n")
        f.write("LOOKUP_TABLE default\n")
        for i in range(grid_size):
            for j in range(grid_size):
                f.write(f"{phase_map[i, j]}\n")

    print(f"  Exported VTK to {output_path}")
    return output_path


def generate_damask_material_yaml(rve_result: Dict,
                                   output_path: str = "material.yaml") -> str:
    """
    生成DAMASK material.yaml配置文件

    基于HPD-RVE的材料参数生成DAMASK格式的材料定义
    """
    import yaml

    # 提取材料参数
    phases = rve_result.get("phases", [])
    grain_summary = {}

    if "grain_summary" in rve_result:
        grain_summary = rve_result["grain_summary"]
    elif "param_files" in rve_result:
        for pf in rve_result["param_files"]:
            for pi in pf.get("phases", []):
                pname = pi["phase_name"]
                if pname not in grain_summary:
                    grain_summary[pname] = {
                        "volume_fraction": pi.get("volume_fraction", 0.5),
                        "lattice_structure": pi.get("lattice_structure", "BCC"),
                    }

    # 构建DAMASK material.yaml
    material_config = {
        "header": {
            "grid": [64, 64, 1],
            "size": [1e-4, 1e-4, 1e-6],
            "homogenization": {"method": "SX", "N_constituents": 1},
        },
        "phase": {},
        "microstructure": {},
    }

    for p_idx, pname in enumerate(grain_summary.keys()):
        structure = grain_summary[pname].get("lattice_structure", "BCC")
        # 根据晶格结构设置参数
        if "FCC" in structure.upper():
            C11, C12, C44 = 168e9, 121e9, 75e9
            lattice = "cF"
        elif "BCT" in structure.upper():
            C11, C12, C44 = 250e9, 150e9, 120e9
            lattice = "tI"
        else:  # BCC
            C11, C12, C44 = 237e9, 141e9, 116e9
            lattice = "cI"

        material_config["phase"][pname] = {
            "lattice": lattice,
            "mechanical": {
                "elastic": {
                    "type": "Hooke",
                    "C_11": C11,
                    "C_12": C12,
                    "C_44": C44,
                },
                "plastic": {
                    "type": "phenopowerlaw",
                    "N_sl": [12],
                    "a_sl": [2.25],
                    "dot_gamma_0_sl": [0.001],
                    "h_0_sl-sl": [1500e6],
                    "h_sat_sl-sl": [250e6],
                    "n_sl": [20],
                    "xi_0_sl": [95e6],
                    "xi_inf_sl": [250e6],
                },
            },
        }

    with open(output_path, 'w', encoding='utf-8') as f:
        yaml.dump(material_config, f, default_flow_style=False, allow_unicode=True)

    print(f"  Generated DAMASK material.yaml: {output_path}")
    return output_path


def generate_damask_load_yaml(loading_mode: str = "uniaxial_tension",
                               strain_rate: float = 0.001,
                               max_strain: float = 0.10,
                               output_path: str = "load.yaml") -> str:
    """
    生成DAMASK loading.yaml配置文件

    Args:
        loading_mode: 加载模式
            - "uniaxial_tension"
            - "plane_strain_tension"
            - "simple_shear"
            - "cyclic"
        strain_rate: 应变率
        max_strain: 最大应变
        output_path: 输出路径
    """
    import yaml

    # 定义不同加载模式的边界条件
    load_configs = {
        "uniaxial_tension": {
            "dot_F": [strain_rate, 0, 0, 0, "x", 0, 0, 0, "x"],
            "P": ["x", "x", "x", "x", 0, "x", "x", "x", 0],
        },
        "plane_strain_tension": {
            "dot_F": [strain_rate, 0, 0, 0, 0, 0, 0, 0, "x"],
            "P": ["x", "x", "x", "x", "x", "x", "x", "x", 0],
        },
        "simple_shear": {
            "dot_F": [0, strain_rate, 0, 0, 0, 0, 0, 0, "x"],
            "P": ["x", "x", "x", "x", "x", "x", "x", "x", 0],
        },
    }

    if loading_mode not in load_configs:
        loading_mode = "uniaxial_tension"

    bc = load_configs[loading_mode]
    t_final = max_strain / strain_rate
    n_steps = 50

    load_config = {
        "solver": {
            "mechanical": "spectral_basic",
        },
        "loadstep": [
            {
                "boundary_conditions": {
                    "mechanical": {
                        "dot_F": bc["dot_F"],
                        "P": bc["P"],
                    }
                },
                "discretization": {
                    "t": t_final,
                    "N": n_steps,
                },
            }
        ],
    }

    with open(output_path, 'w', encoding='utf-8') as f:
        yaml.dump(load_config, f, default_flow_style=False, allow_unicode=True)

    print(f"  Generated DAMASK load.yaml ({loading_mode}): {output_path}")
    return output_path


